# Setup Android SDK command-line tools untuk build APK/AAB smile-2.1
# Jalankan: powershell -ExecutionPolicy Bypass -File scripts/setup-android-sdk.ps1

$ErrorActionPreference = "Stop"

$SdkRoot = Join-Path $env:LOCALAPPDATA "Android\Sdk"
$CmdlineToolsDir = Join-Path $SdkRoot "cmdline-tools\latest"
$ZipPath = Join-Path $env:TEMP "android-cmdline-tools.zip"
$CmdlineUrl = "https://dl.google.com/android/repository/commandlinetools-win-11076708_latest.zip"

Write-Host "==> Android SDK root: $SdkRoot"

New-Item -ItemType Directory -Force -Path $CmdlineToolsDir | Out-Null

if (-not (Test-Path (Join-Path $CmdlineToolsDir "bin\sdkmanager.bat"))) {
    Write-Host "==> Downloading Android command-line tools..."
    Invoke-WebRequest -Uri $CmdlineUrl -OutFile $ZipPath -UseBasicParsing

    $ExtractDir = Join-Path $env:TEMP "android-cmdline-tools-extract"
    if (Test-Path $ExtractDir) { Remove-Item $ExtractDir -Recurse -Force }
    Expand-Archive -Path $ZipPath -DestinationPath $ExtractDir -Force

    # Zip berisi folder cmdline-tools/ — pindahkan isinya ke latest/
    $Inner = Join-Path $ExtractDir "cmdline-tools"
    if (Test-Path $Inner) {
        Get-ChildItem $Inner | Copy-Item -Destination $CmdlineToolsDir -Recurse -Force
    } else {
        Get-ChildItem $ExtractDir | Copy-Item -Destination $CmdlineToolsDir -Recurse -Force
    }

    Remove-Item $ZipPath -Force -ErrorAction SilentlyContinue
    Remove-Item $ExtractDir -Recurse -Force -ErrorAction SilentlyContinue
    Write-Host "==> Command-line tools installed."
} else {
    Write-Host "==> Command-line tools already present."
}

$env:ANDROID_HOME = $SdkRoot
$env:ANDROID_SDK_ROOT = $SdkRoot

# Temukan JAVA_HOME jika belum diset
if (-not $env:JAVA_HOME) {
    $java = Get-ChildItem "C:\Program Files\Eclipse Adoptium" -Recurse -Filter "java.exe" -ErrorAction SilentlyContinue |
        Where-Object { $_.FullName -like "*\bin\java.exe" } | Select-Object -First 1
    if ($java) {
        $env:JAVA_HOME = Split-Path (Split-Path $java.FullName)
    }
}

if (-not $env:JAVA_HOME) {
    throw "JAVA_HOME tidak ditemukan. Install JDK 17 terlebih dahulu."
}

Write-Host "==> JAVA_HOME: $env:JAVA_HOME"

$SdkManager = Join-Path $CmdlineToolsDir "bin\sdkmanager.bat"
$LicenseInput = ("y`n" * 50)

Write-Host "==> Accepting Android SDK licenses..."
$LicenseInput | & $SdkManager --sdk_root=$SdkRoot --licenses 2>&1 | Out-Null

Write-Host "==> Installing SDK packages (platform-tools, build-tools, android-35)..."
$packages = @(
    "platform-tools",
    "build-tools;35.0.0",
    "platforms;android-35"
)

$LicenseInput | & $SdkManager --sdk_root=$SdkRoot @packages 2>&1

# Tulis local.properties untuk Gradle
$ProjectRoot = Split-Path $PSScriptRoot -Parent
$LocalProps = Join-Path $ProjectRoot "local.properties"
$EscapedSdk = $SdkRoot -replace "\\", "\\\\"
@"
## Auto-generated by setup-android-sdk.ps1
sdk.dir=$EscapedSdk
"@ | Set-Content -Path $LocalProps -Encoding UTF8

Write-Host ""
Write-Host "==> Selesai!"
Write-Host "    SDK: $SdkRoot"
Write-Host "    local.properties: $LocalProps"
Write-Host ""
Write-Host "Build APK debug:"
Write-Host "  cd $ProjectRoot"
Write-Host "  .\gradlew.bat :composeApp:assembleDebug"
Write-Host ""
Write-Host "Build AAB release (butuh keystore.properties):"
Write-Host "  .\gradlew.bat :composeApp:bundleRelease"
